use std::io::Cursor;

use crate::parser::nfsv3::mk_dir::args;
use crate::vfs::set_attr;

#[test]
fn test_mkdir() {
    #[rustfmt::skip]
    const DATA: &[u8] = &[
        0x00, 0x00, 0x00, 0x09, 0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07, 0x08, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x04, b'd', b'i', b'r', b'1',
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x25,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01,
        0x00, 0x00, 0x00, 0x01,
    ];

    let result = args(&mut Cursor::new(DATA)).unwrap();

    assert_eq!(result.object.dir.0, [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08]);
    assert_eq!(result.object.name.as_str(), "dir1");
    assert!(matches!(
        result.attr,
        set_attr::NewAttr {
            mode: Some(0x25),
            uid: None,
            gid: None,
            size: None,
            atime: set_attr::SetTime::ToServer,
            mtime: set_attr::SetTime::ToServer,
        }
    ));
}
