use std::io::Cursor;

use crate::parser::nfsv3::read_link::args;

#[test]
fn test_readlink() {
    #[rustfmt::skip]
    const DATA: &[u8] = &[
        0x00, 0x00, 0x00, 0x09, 0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07, 0x08, 0x00, 0x00, 0x00,
    ];

    let result = args(&mut Cursor::new(DATA)).unwrap();

    assert_eq!(result.file.0, [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08])
}
