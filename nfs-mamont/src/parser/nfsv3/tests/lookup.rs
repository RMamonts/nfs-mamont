use std::io::Cursor;

use crate::parser::nfsv3::lookup::args;

#[test]
fn test_lookup() {
    #[rustfmt::skip]
    const DATA: &[u8] = &[
        0x00, 0x00, 0x00, 0x09, 0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07, 0x08, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x04, b't', b'e', b's', b't',
    ];

    let args = args(&mut Cursor::new(DATA)).unwrap();

    assert_eq!(args.parent.0, [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08]);
    assert_eq!(args.name.as_str(), "test");
}

#[test]
fn test_lookup_unaligned_name() {
    #[rustfmt::skip]
    const DATA: &[u8] = &[
        0x00, 0x00, 0x00, 0x09, 0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07, 0x08, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x03, b'a', b'b', b'c',
    ];

    let result = args(&mut Cursor::new(DATA));
    assert!(result.is_err());
}
