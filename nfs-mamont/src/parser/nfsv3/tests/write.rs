use std::io::Cursor;

use crate::parser::nfsv3::write::args;
use crate::vfs::write;

#[test]
fn test_write() {
    #[rustfmt::skip]
    const DATA: &[u8] = &[
        0x00, 0x00, 0x00, 0x09, 0x00, 0x01, 0x02, 0x03,
        0x04, 0x05, 0x06, 0x07, 0x08, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00,
        0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x00, 0x00,
    ];

    let result = args(&mut Cursor::new(DATA)).unwrap();

    assert_eq!(result.file.0, [0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08]);
    assert_eq!(result.offset, 65536);
    assert_eq!(result.size, 1024);
    assert!(matches!(result.stable, write::StableHow::Unstable));
}
